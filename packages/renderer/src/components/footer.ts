import type { ExplainerDocument, SkipReason } from '@lucidiff/core/schema';
import { html, type SafeHtml } from '../html';
import { formatNumber, plural } from '../text';

const SKIP_LABELS: Record<SkipReason, string> = {
  ignored: 'ignore list',
  binary: 'binary file',
  generated: 'generated file',
  'too-large': 'too large',
};

function formatDate(iso: string): string {
  const date = new Date(iso);
  // Fixed format and UTC, so the same document always renders the same text.
  return `${date.toISOString().slice(0, 16).replace('T', ' ')} UTC`;
}

/** Model, generation details, skipped files, and the AI disclaimer. */
export function footer(doc: ExplainerDocument): SafeHtml {
  const { meta } = doc;
  const tokens = meta.usage.total_tokens;
  const rows: [string, SafeHtml | string][] = [
    ['Model', html`<code>${meta.model}</code>`],
    ['Provider', meta.provider],
    [
      'Generated',
      html`<time datetime="${meta.generated_at}">${formatDate(meta.generated_at)}</time>`,
    ],
    [
      'Analysis',
      meta.mode === 'batched'
        ? `Batched (${plural(meta.usage.llm_calls, 'model call')})`
        : plural(meta.usage.llm_calls, 'model call'),
    ],
    [
      'Tokens',
      tokens > 0
        ? `${formatNumber(meta.usage.input_tokens)} in · ${formatNumber(meta.usage.output_tokens)} out`
        : 'Not reported',
    ],
    [
      'Files analyzed',
      `${formatNumber(meta.stats.files_analyzed)} of ${formatNumber(meta.stats.files_changed)}`,
    ],
    ['Secrets redacted', formatNumber(meta.redactions)],
    ['Risks dropped', `${formatNumber(meta.dropped_risks)} (invalid citation)`],
  ];

  return html`<footer class="footer">
    <div class="disclaimer" role="note">
      <strong>AI-generated.</strong> A language model wrote this explainer from the diff. It can be
      wrong or incomplete. Use it to guide your review. It does not replace reading the code.
    </div>
    <dl class="meta-grid">
      ${rows.map(
        ([label, value]) =>
          html`<div>
            <dt>${label}</dt>
            <dd>${value}</dd>
          </div>`,
      )}
    </dl>
    ${
      doc.skipped_files.length > 0
        ? html`<details class="skipped">
            <summary>${plural(doc.skipped_files.length, 'file')} not sent to the model</summary>
            <ul>
              ${doc.skipped_files.map(
                (skipped) =>
                  html`<li>
                    <code>${skipped.file}</code>
                    <span class="muted">${SKIP_LABELS[skipped.reason]}</span>
                  </li>`,
              )}
            </ul>
          </details>`
        : ''
    }
    <p class="colophon">
      Generated by ${meta.tool.name} ${meta.tool.version} · schema v${doc.schema_version}
    </p>
  </footer>`;
}
