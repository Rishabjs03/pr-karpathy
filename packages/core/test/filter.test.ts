import { describe, expect, it } from 'vitest';
import { filterFiles } from '../src/prepare/filter';
import type { DiffFile } from '../src/diff/types';

function file(path: string, overrides: Partial<DiffFile> = {}): DiffFile {
  return {
    path,
    oldPath: path,
    newPath: path,
    kind: 'modified',
    binary: false,
    hunks: [
      {
        oldStart: 1,
        oldLines: 1,
        newStart: 1,
        newLines: 1,
        section: '',
        lines: [{ type: 'add', content: 'x', oldLine: null, newLine: 1 }],
      },
    ],
    additions: 1,
    deletions: 0,
    ...overrides,
  };
}

const paths = (files: DiffFile[]) => files.map((f) => f.path);

describe('filterFiles', () => {
  it('skips lockfiles, build output, minified files, and snapshots anywhere in the tree', () => {
    const { files, skipped } = filterFiles([
      file('src/index.ts'),
      file('pnpm-lock.yaml'),
      file('apps/web/package-lock.json'),
      file('services/api/go.sum'),
      file('dist/index.js'),
      file('packages/ui/build/out.js'),
      file('public/vendor.min.js'),
      file('src/__snapshots__/a.test.ts.snap'),
      file('assets/logo.PNG'),
    ]);
    expect(paths(files)).toEqual(['src/index.ts']);
    expect(skipped.every((entry) => entry.reason === 'ignored')).toBe(true);
    expect(skipped).toHaveLength(8);
  });

  it('skips binary files', () => {
    const { skipped } = filterFiles([file('data.bin', { binary: true })]);
    expect(skipped).toEqual([{ file: 'data.bin', reason: 'binary' }]);
  });

  it('skips files with a generated marker', () => {
    const generated = file('src/api/client.ts', {
      hunks: [
        {
          oldStart: 0,
          oldLines: 0,
          newStart: 1,
          newLines: 1,
          section: '',
          lines: [
            {
              type: 'add',
              content: '// Code generated by openapi-gen. DO NOT EDIT.',
              oldLine: null,
              newLine: 1,
            },
          ],
        },
      ],
    });
    expect(filterFiles([generated]).skipped).toEqual([
      { file: 'src/api/client.ts', reason: 'generated' },
    ]);
  });

  it('skips files with too many changed lines', () => {
    expect(filterFiles([file('big.sql', { additions: 9000 })]).skipped).toEqual([
      { file: 'big.sql', reason: 'too-large' },
    ]);
    expect(
      filterFiles([file('big.sql', { additions: 9000 })], { maxChangedLines: 10_000 }).files,
    ).toHaveLength(1);
  });

  it('applies extra ignore patterns', () => {
    const { files } = filterFiles([file('src/a.ts'), file('docs/guide.md')], {
      ignore: ['docs/**'],
    });
    expect(paths(files)).toEqual(['src/a.ts']);
  });

  it('lets include patterns override ignores', () => {
    const { files } = filterFiles([file('pnpm-lock.yaml'), file('dist/a.js')], {
      include: ['pnpm-lock.yaml'],
    });
    expect(paths(files)).toEqual(['pnpm-lock.yaml']);
  });

  it('can turn the default ignore list off', () => {
    const { files } = filterFiles([file('yarn.lock')], { defaultIgnores: false });
    expect(paths(files)).toEqual(['yarn.lock']);
  });

  it('matches renamed files by their new path', () => {
    const outOfDist = file('src/kept.ts', { kind: 'renamed', oldPath: 'dist/old.js' });
    const intoDist = file('dist/moved.js', { kind: 'renamed', oldPath: 'src/moved.js' });
    const { files, skipped } = filterFiles([outOfDist, intoDist]);
    expect(paths(files)).toEqual(['src/kept.ts']);
    expect(skipped).toEqual([{ file: 'dist/moved.js', reason: 'ignored' }]);
  });
});
