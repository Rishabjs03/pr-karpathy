/**
 * Decides which changed files the model sees.
 *
 * Lockfiles, build output, minified bundles, and binaries are noise for a reviewer and cost
 * tokens, so they are skipped by default. Skipped files are still listed in the explainer, so
 * the reviewer knows they exist and can review them by hand.
 */
import picomatch from 'picomatch';
import type { DiffFile } from '../diff/types';
import type { SkippedFile } from '../schema/document';

/** Glob patterns skipped unless `defaultIgnores` is false. Matched against the full path. */
export const DEFAULT_IGNORE_PATTERNS: readonly string[] = [
  // Lockfiles
  '**/pnpm-lock.yaml',
  '**/package-lock.json',
  '**/npm-shrinkwrap.json',
  '**/yarn.lock',
  '**/bun.lock',
  '**/bun.lockb',
  '**/Cargo.lock',
  '**/Gemfile.lock',
  '**/composer.lock',
  '**/poetry.lock',
  '**/Pipfile.lock',
  '**/uv.lock',
  '**/go.sum',
  '**/flake.lock',
  '**/Podfile.lock',
  '**/pubspec.lock',
  '**/mix.lock',
  '**/packages.lock.json',
  '**/gradle.lockfile',
  '**/*.lock',
  // Build output and vendored code
  '**/dist/**',
  '**/build/**',
  '**/node_modules/**',
  '**/vendor/**',
  '**/coverage/**',
  '**/.next/**',
  '**/__snapshots__/**',
  '**/*.snap',
  // Minified and generated code
  '**/*.min.js',
  '**/*.min.mjs',
  '**/*.min.css',
  '**/*.map',
  '**/*.generated.*',
  '**/*.pb.go',
  '**/*_pb2.py',
  '**/*_pb2_grpc.py',
  // Binary formats (git usually marks these as binary already)
  '**/*.{png,jpg,jpeg,gif,webp,avif,ico,bmp,tiff,psd}',
  '**/*.{woff,woff2,ttf,otf,eot}',
  '**/*.{zip,gz,tgz,bz2,xz,7z,rar,jar,war}',
  '**/*.{mp3,mp4,mov,wav,webm,ogg,flac}',
  '**/*.{pdf,exe,dll,so,dylib,wasm,class,pyc,o,a}',
];

/** Text that marks a file as generated, found in its first added lines. */
const GENERATED_MARKER =
  /@generated|DO NOT EDIT|auto-generated|autogenerated by|generated by .* do not modify/i;

export interface FilterOptions {
  /** Skip files that match these globs, in addition to the defaults. */
  ignore?: readonly string[];
  /** Always include files that match these globs, even if an ignore pattern matches. */
  include?: readonly string[];
  /** Use `DEFAULT_IGNORE_PATTERNS`. Default true. */
  defaultIgnores?: boolean;
  /** Skip a single file with more changed lines than this. Default 5000. */
  maxChangedLines?: number;
}

export interface FilterResult {
  files: DiffFile[];
  skipped: SkippedFile[];
}

function looksGenerated(file: DiffFile): boolean {
  const firstLines = file.hunks
    .flatMap((hunk) => hunk.lines)
    .filter((line) => line.type !== 'delete')
    .slice(0, 8);
  return firstLines.some((line) => GENERATED_MARKER.test(line.content));
}

/** Splits files into the ones the model sees and the ones it skips, with a reason. */
export function filterFiles(files: readonly DiffFile[], options: FilterOptions = {}): FilterResult {
  const patterns = [
    ...(options.defaultIgnores === false ? [] : DEFAULT_IGNORE_PATTERNS),
    ...(options.ignore ?? []),
  ];
  const matchOptions = { dot: true, nocase: true };
  const isIgnored =
    patterns.length > 0 ? picomatch(patterns as string[], matchOptions) : () => false;
  const isIncluded =
    options.include && options.include.length > 0
      ? picomatch(options.include as string[], matchOptions)
      : () => false;
  const maxChangedLines = options.maxChangedLines ?? 5000;

  const kept: DiffFile[] = [];
  const skipped: SkippedFile[] = [];
  for (const file of files) {
    // Match the path the file has after the change (the old path only for deletions). A file
    // moved out of `dist/` into `src/` is source code now.
    const forced = isIncluded(file.path);
    if (file.binary) skipped.push({ file: file.path, reason: 'binary' });
    else if (!forced && isIgnored(file.path)) skipped.push({ file: file.path, reason: 'ignored' });
    else if (!forced && looksGenerated(file))
      skipped.push({ file: file.path, reason: 'generated' });
    else if (file.additions + file.deletions > maxChangedLines) {
      skipped.push({ file: file.path, reason: 'too-large' });
    } else kept.push(file);
  }
  return { files: kept, skipped };
}
